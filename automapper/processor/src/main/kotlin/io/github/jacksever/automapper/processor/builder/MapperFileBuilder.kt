package io.github.jacksever.automapper.processor.builder

import com.google.devtools.ksp.processing.KSPLogger
import com.google.devtools.ksp.symbol.KSClassDeclaration
import com.google.devtools.ksp.symbol.Modifier
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.KModifier
import io.github.jacksever.automapper.processor.exception.MappingException
import io.github.jacksever.automapper.processor.model.MapperDefinition
import io.github.jacksever.automapper.processor.resolver.MappingSignatureResolver
import io.github.jacksever.automapper.processor.resolver.MappingTypeResolver

/**
 * Defines the contract for building an in-memory mapper [FileSpec]
 *
 * Implementations assemble extension functions for the configured mapping directions.
 * Writing the resulting source file and tracking KSP dependencies remain the caller's responsibility
 */
internal interface MapperFileBuilder {

    /**
     * Builds a mapper file containing forward mappings and any requested reverse mappings
     *
     * Generated signatures are validated before functions are assembled. The module determines
     * function visibility. The header identifies the generator, source module, and source file name.
     * This method does not write the file
     *
     * @param fileName generated file name without the extension
     * @param packageName package of the generated file
     * @param types type resolver belonging to the current KSP round
     * @param module mapper module supplying visibility and diagnostic context
     * @param mappers original mapping declarations, including their reverse-generation settings
     * @return complete KotlinPoet file ready to be written by the caller
     * @throws MappingException if generated signatures conflict or a mapping cannot be generated
     */
    fun buildMapperFile(
        fileName: String,
        packageName: String,
        types: MappingTypeResolver,
        module: KSClassDeclaration,
        mappers: List<MapperDefinition>,
    ): FileSpec
}

/**
 * Default implementation of [MapperFileBuilder]
 *
 * Expands reverse mappings and delegates signature validation and JVM naming to [MappingSignatureResolver].
 * Functions are generated by [MapperFunctionBuilder], then combined with the module's file header
 * and visibility settings
 *
 * @param logger logger shared by signature resolution and function generation
 */
internal class MapperFileBuilderImpl(logger: KSPLogger) : MapperFileBuilder {

    private val functionBuilder = MapperFunctionBuilder(logger = logger)
    private val signatureResolver = MappingSignatureResolver(logger = logger)

    override fun buildMapperFile(
        fileName: String,
        packageName: String,
        types: MappingTypeResolver,
        module: KSClassDeclaration,
        mappers: List<MapperDefinition>,
    ): FileSpec {
        val definitions = mappers.flatMap { definition ->
            if (definition.reversible) listOf(definition, definition.reversed()) else listOf(
                definition
            )
        }
        val mappings = signatureResolver.resolve(module = module, definitions = definitions)
        val visibility =
            if (Modifier.INTERNAL in module.modifiers) KModifier.INTERNAL else KModifier.PUBLIC
        val functions = mappings.map { mapping ->
            functionBuilder.build(mapping = mapping, types = types, visibility = visibility)
        }

        return FileSpec.builder(fileName = fileName, packageName = packageName)
            .indent(indent = "    ")
            .addFileComment(
                format = "Generated by AutoMapperProcessor. Do not edit.\nSource: %L\nFile: %L",
                module.qualifiedName?.asString() ?: module.simpleName.asString(),
                module.containingFile?.fileName ?: "Unknown",
            )
            .addFunctions(funSpecs = functions)
            .build()
    }
}
